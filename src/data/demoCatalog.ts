function buildDefaultFieldConfidences(
  attributes: Record<string, string | boolean>,
): Record<string, ConfidenceLevel> {
  const out: Record<string, ConfidenceLevel> = {};
  for (const k of Object.keys(attributes)) {
    out[k] = 'high';
  }
  return out;
}

function hydrateDemoCatalog(): {
  collections: CollectionRecord[];
  items: CollectibleItemRecord[];
} {
  const userByHandle = new Map(DEMO_USERS.map((u) => [u.handle, u]));
  const collections: CollectionRecord[] = [];
  const items: CollectibleItemRecord[] = [];

  RAW_COLLECTIONS.forEach((colSpec, colIdx) => {
    const owner = userByHandle.get(colSpec.ownerHandle) || DEMO_USERS[0];
    let minTotal = 0;
    let maxTotal = 0;
    let firstImage = colSpec.coverImageUrl || '';

    colSpec.pieces.forEach((piece, pieceIdx) => {
      const placard = getItemPlacardParts(colSpec.category, piece.attributes);
      const artUrl =
        piece.photoUrl ||
        buildCollectorArtDataUrl({
          category: colSpec.category,
          title: piece.title,
          subtitle: placard.maker,
          year: placard.year,
          code: placard.catNumber,
          grade: placard.condition,
          accentSeed: colIdx * 13 + pieceIdx,
        });

      if (!firstImage) firstImage = artUrl;

      const photos: ItemPhoto[] = [
        {
          url: artUrl,
          thumbUrl: artUrl,
          width: 800,
          height: colSpec.category === 'coins' || colSpec.category === 'vinyl' ? 800 : 1000,
          label: colSpec.category === 'coins' ? 'Obverse' : 'Front',
        },
      ];

      if (piece.backPhotoUrl) {
        photos.push({
          url: piece.backPhotoUrl,
          thumbUrl: piece.backPhotoUrl,
          width: 800,
          height: colSpec.category === 'coins' ? 800 : 1000,
          label: colSpec.category === 'coins' ? 'Reverse' : 'Back',
        });
      }

      minTotal += piece.valueMinGbp;
      maxTotal += piece.valueMaxGbp;

      const itemId = `demo_itm_${colIdx + 1}_${String(pieceIdx + 1).padStart(2, '0')}`;

      items.push({
        id: itemId,
        collectionId: colSpec.id,
        ownerId: owner.uid,
        ownerHandle: owner.handle,
        category: colSpec.category,
        visibility: 'public',
        title: piece.title,
        titleLower: piece.title.toLowerCase(),
        story: piece.story,
        imageUrl: artUrl,
        thumbUrl: artUrl,
        photos,
        attributes: piece.attributes,
        fieldConfidences: buildDefaultFieldConfidences(piece.attributes),
        year: placard.year,
        maker: placard.maker,
        setNumber: placard.catNumber,
        condition: placard.condition || 'Good',
        valueMinGbp: piece.valueMinGbp,
        valueMaxGbp: piece.valueMaxGbp,
        valuationReason: piece.valuationReason,
        aiConfidence: 'high',
        grail: Boolean(piece.grail),
        tags: piece.tags,
        customOrder: pieceIdx,
        forSale: false,
        mediaCredit: piece.mediaCredit,
        panelStatus: pieceIdx % 2 === 0 ? 'confirmed' : 'none',
        panelConfirmedAt: pieceIdx % 2 === 0 ? '12 Oct 2024' : undefined,
        isDemo: true,
      });
    });

    collections.push({
      id: colSpec.id,
      ownerId: owner.uid,
      ownerName: owner.displayName,
      ownerHandle: owner.handle,
      title: colSpec.title,
      story: colSpec.story,
      coverImageUrl: firstImage,
      category: colSpec.category,
      visibility: 'public',
      itemCount: colSpec.pieces.length,
      setTargetCount: colSpec.setTargetCount,
      estimatedTotalMinGbp: minTotal,
      estimatedTotalMaxGbp: maxTotal,
      featured: colSpec.featured,
      isDemo: true,
    });
  });

  return { collections, items };
}

